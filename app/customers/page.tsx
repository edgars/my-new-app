"use client";
import { useState } from "react";
import useSWR from "swr";
import Link from "next/link";
import { Plus, Search, Pencil, Inbox } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Table, TableHeader, TableBody, TableRow, TableHead, TableCell } from "@/components/ui/table";
import { Skeleton } from "@/components/ui/skeleton";

const fetcher = (url: string) => fetch(url).then((r) => r.json());
const PAGE_SIZE = 20;

// Customers — list view, generated by RNC from the UIR.
export default function CustomersPage() {
  const [page, setPage] = useState(1);
  const [query, setQuery] = useState("");
  const { data, isLoading } = useSWR(`/api/customers?page=${page}&limit=${PAGE_SIZE}`, fetcher);

  const rows: any[] = data?.data ?? [];
  const total: number = data?.total ?? 0;
  const totalPages = Math.max(1, Math.ceil(total / PAGE_SIZE));

  const filtered = query
    ? rows.filter((row) =>
        Object.values(row).some((v) => String(v ?? "").toLowerCase().includes(query.toLowerCase())),
      )
    : rows;

  return (
    <div className="container mx-auto max-w-6xl px-4 py-8">
      <div className="mb-6 flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="text-2xl font-bold tracking-tight">Customers</h1>
          <p className="text-sm text-muted-foreground">{total} record{total === 1 ? "" : "s"}</p>
        </div>
        <Button asChild>
          <Link href="/customers/new"><Plus className="h-4 w-4" /> New Ed Cust</Link>
        </Button>
      </div>

      <Card>
        <CardHeader className="flex flex-row items-center justify-between gap-4 space-y-0">
          <CardTitle className="text-base">All Customers</CardTitle>
          <div className="relative w-full max-w-xs">
            <Search className="absolute left-2.5 top-2.5 h-4 w-4 text-muted-foreground" />
            <Input
              placeholder="Search…"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              className="pl-8"
            />
          </div>
        </CardHeader>
        <CardContent>
          {isLoading ? (
            <div className="space-y-2">
              <Skeleton className="h-10 w-full" />
              <Skeleton className="h-10 w-full" />
              <Skeleton className="h-10 w-full" />
            </div>
          ) : filtered.length === 0 ? (
            <div className="flex flex-col items-center justify-center gap-2 py-16 text-center">
              <Inbox className="h-10 w-10 text-muted-foreground" />
              <p className="font-medium">No Customers found</p>
              <p className="text-sm text-muted-foreground">
                {query ? "Try a different search." : "Create the first record to get started."}
              </p>
              {!query && (
                <Button asChild variant="outline" className="mt-2">
                  <Link href="/customers/new"><Plus className="h-4 w-4" /> New Ed Cust</Link>
                </Button>
              )}
            </div>
          ) : (
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Company</TableHead>
                  <TableHead>Address 1</TableHead>
                  <TableHead>Address 2</TableHead>
                  <TableHead>City</TableHead>
                  <TableHead>State</TableHead>
                  <TableHead>Zip</TableHead>
                  <TableHead>Country</TableHead>
                  <TableHead>Phone</TableHead>
                  <TableHead>Tax Rate</TableHead>
                  <TableHead>Contact</TableHead>
                  <TableHead>Last Invoice Date</TableHead>
                  <TableHead>Fax</TableHead>
                  <TableHead className="w-0" />
                </TableRow>
              </TableHeader>
              <TableBody>
                {filtered.map((row) => (
                  <TableRow key={row.id}>
                    <TableCell>{String(row.company ?? "")}</TableCell>
                    <TableCell>{String(row.addr1 ?? "")}</TableCell>
                    <TableCell>{String(row.addr2 ?? "")}</TableCell>
                    <TableCell>{String(row.city ?? "")}</TableCell>
                    <TableCell>{String(row.state ?? "")}</TableCell>
                    <TableCell>{String(row.zip ?? "")}</TableCell>
                    <TableCell>{String(row.country ?? "")}</TableCell>
                    <TableCell>{String(row.phone ?? "")}</TableCell>
                    <TableCell>{String(row.taxRate ?? "")}</TableCell>
                    <TableCell>{String(row.contact ?? "")}</TableCell>
                    <TableCell>{String(row.lastInvoiceDate ?? "")}</TableCell>
                    <TableCell>{String(row.fax ?? "")}</TableCell>
                    <TableCell className="text-right">
                      <Button variant="ghost" size="sm" asChild>
                        <Link href={`/customers/${row.id}/edit`}><Pencil className="h-4 w-4" /> Edit</Link>
                      </Button>
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          )}
        </CardContent>
      </Card>

      {totalPages > 1 && (
        <div className="mt-4 flex items-center justify-end gap-2">
          <span className="text-sm text-muted-foreground">Page {page} of {totalPages}</span>
          <Button variant="outline" size="sm" disabled={page <= 1} onClick={() => setPage((p) => p - 1)}>
            Previous
          </Button>
          <Button variant="outline" size="sm" disabled={page >= totalPages} onClick={() => setPage((p) => p + 1)}>
            Next
          </Button>
        </div>
      )}
    </div>
  );
}
